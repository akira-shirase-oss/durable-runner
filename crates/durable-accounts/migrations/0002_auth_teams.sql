-- The mail outbox (D-068): every mail is a row written in the same
-- transaction as the fact that needs it, so a lost send is a pending
-- row, never a lost mail. The claim transition pending -> sending is
-- the dedupe; attempts and next_attempt_at bound retries. 'dropped'
-- rows are intentionally-dead mail (the token expired) with bodies
-- cleared; expires_at is what the sweep drops on.
CREATE TABLE email_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,                     -- verify|reset|invite|notice
    send_to TEXT NOT NULL,
    subject TEXT NOT NULL,
    text TEXT NOT NULL,
    html TEXT NOT NULL,
    idempotency_key TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'sent', 'failed', 'dropped')),
    attempts INT NOT NULL DEFAULT 0,
    last_error TEXT,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,                 -- the token's expiry; NULL = send whenever
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at TIMESTAMPTZ
);
-- The drain scans due rows in both live states: a stale 'sending'
-- (worker died between claim and mark) is reclaimable once its
-- claim deadline passes.
CREATE INDEX outbox_due ON email_outbox (next_attempt_at)
    WHERE status IN ('pending', 'sending');
