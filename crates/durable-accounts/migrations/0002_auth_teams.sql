-- S3: accounts become sign-up-able, sessions become real, plans and
-- invites arrive, mail gets an outbox. The journal remains the only
-- authority for jobs; nothing here is read on the commit path.
--
-- Neon-safe: no CREATE EXTENSION beyond what 0001 did (pgcrypto is a
-- trusted extension on Neon and already present), no ALTER OWNER, no
-- superuser constructs. Partial indexes only where the predicate is
-- immutable (a status literal is fine; now() would not be).

-- Roles widen to the S3 set and gain a "member since" timestamp; the
-- one-owner invariant is a partial unique index (each workspace keeps
-- exactly one owner row).
ALTER TABLE members DROP CONSTRAINT members_role_check;
ALTER TABLE members
    ADD CONSTRAINT members_role_check
    CHECK (role IN ('owner', 'admin', 'member', 'viewer'));
ALTER TABLE members ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now();
CREATE UNIQUE INDEX members_one_owner ON members (workspace_id)
    WHERE role = 'owner';

-- Accounts become externally addressable (opaque UUIDv7 — internal ids
-- never leave the process) and gain the verification fact. Email is
-- stored lower-cased; the CHECK keeps a row from being written any
-- other way.
ALTER TABLE accounts
    ADD COLUMN public_id UUID,
    ADD COLUMN email_verified_at TIMESTAMPTZ;
UPDATE accounts SET public_id = gen_random_uuid() WHERE public_id IS NULL;
ALTER TABLE accounts ALTER COLUMN public_id SET NOT NULL;
CREATE UNIQUE INDEX accounts_public_id ON accounts (public_id);
ALTER TABLE accounts
    ADD CONSTRAINT accounts_email_lc
    CHECK (email = lower(email) AND position('@' IN email) > 1);

-- Sessions become real: opaque token hashed at rest, idle + absolute
-- expiry, revocation, rotation linkage, the CSRF seed (its derived
-- token is never stored — D-065), and the bookkeeping the sessions
-- page shows.
ALTER TABLE sessions
    ADD COLUMN public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    -- No default on the seed (review #11): a defaulted zero would mint
    -- the publicly computable CSRF token HMAC(0, "csrf") for any row
    -- that forgot to bind it. Backfill, then constrain.
    ADD COLUMN csrf_seed BYTEA;
UPDATE sessions SET csrf_seed = gen_random_bytes(32) WHERE csrf_seed IS NULL;
ALTER TABLE sessions
    ALTER COLUMN csrf_seed SET NOT NULL,
    ADD CONSTRAINT sessions_csrf_seed_len CHECK (octet_length(csrf_seed) = 32),
    ADD COLUMN last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN idle_expires_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN revoked_at TIMESTAMPTZ,
    ADD COLUMN replaced_by BIGINT REFERENCES sessions (id),
    ADD COLUMN user_agent TEXT,
    ADD COLUMN ip INET;
CREATE UNIQUE INDEX sessions_public_id ON sessions (public_id);
CREATE INDEX sessions_account_live ON sessions (account_id)
    WHERE revoked_at IS NULL;

