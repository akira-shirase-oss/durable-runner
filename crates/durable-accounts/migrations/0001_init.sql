-- Account graph for S2. The journal remains the only authority for jobs;
-- this schema holds accounts, workspaces, members, API keys, handler
-- registrations, plan limits and per-workspace signing secrets. Internal
-- workspace ids are u64; anything external uses workspaces.public_id
-- (UUIDv7) so sequential ids are never enumerable from outside.

CREATE TABLE IF NOT EXISTS workspaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    name TEXT NOT NULL,
    handler_secret BYTEA NOT NULL,
    plan_limits JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Workspace 0 is the default workspace: every journal written before S2
-- decodes as ws 0, and the env ops keys grant ws 0. Seeded once.
INSERT INTO workspaces (id, public_id, name, handler_secret)
VALUES (
    0,
    '00000000-0000-0000-0000-000000000000',
    'default',
    decode(
        md5(random()::text || clock_timestamp()::text || random()::text),
        'hex'
    )
)
ON CONFLICT (id) DO NOTHING;

SELECT setval(
    pg_get_serial_sequence('workspaces', 'id'),
    GREATEST((SELECT COALESCE(MAX(id), 1) FROM workspaces), 1)
);

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS members (
    workspace_id BIGINT NOT NULL REFERENCES workspaces (id),
    account_id BIGINT NOT NULL REFERENCES accounts (id),
    role TEXT NOT NULL CHECK (role IN ('admin', 'member')),
    PRIMARY KEY (workspace_id, account_id)
);

CREATE TABLE IF NOT EXISTS api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspaces (id),
    name TEXT NOT NULL,
    key_hash BYTEA NOT NULL UNIQUE,
    prefix TEXT NOT NULL,
    permission TEXT NOT NULL CHECK (permission IN ('admin', 'read')),
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS handler_registrations (
    workspace_id BIGINT NOT NULL REFERENCES workspaces (id),
    name TEXT NOT NULL,
    url TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, name)
);

-- Sessions are reserved for the S3 dashboard login; the table exists so
-- the account graph is complete but nothing reads or writes it yet.
CREATE TABLE IF NOT EXISTS sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts (id),
    token_hash BYTEA NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
