-- S3-7: workflows — a named, versioned spec a workspace runs on demand.
-- Versions are immutable (no UPDATE path exists); a patch inserts the
-- next version row. Runs are journaled here only as bookkeeping — the
-- engine's journal is their truth; this table exists for listing and
-- the 7-day purge.

CREATE TABLE workflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    workspace_id BIGINT NOT NULL REFERENCES workspaces (id),
    name TEXT NOT NULL,
    created_by BIGINT REFERENCES accounts (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    archived_at TIMESTAMPTZ
);
CREATE INDEX workflows_live ON workflows (workspace_id)
    WHERE archived_at IS NULL;

-- Immutable: (workflow_id, version) is written once, never updated.
CREATE TABLE workflow_versions (
    workflow_id BIGINT NOT NULL REFERENCES workflows (id),
    version INT NOT NULL,
    spec JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workflow_id, version)
);

-- One row per accepted engine run a "run now" minted — the listing
-- source and the purge's scan target.
CREATE TABLE workflow_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT NOT NULL REFERENCES workflows (id),
    workspace_id BIGINT NOT NULL,
    version INT NOT NULL,
    op_key TEXT NOT NULL,
    run_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX workflow_runs_by_workflow ON workflow_runs (workflow_id, created_at DESC);
-- The run-now dedup anchor: one row per op key — a replayed
-- Idempotency-Key finds it and re-answers instead of re-running.
CREATE UNIQUE INDEX workflow_runs_op ON workflow_runs (workflow_id, op_key);
CREATE INDEX workflow_runs_purge ON workflow_runs (created_at);
